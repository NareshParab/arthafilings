#!/usr/bin/env node
// Scans frontend/src for [VERIFY], [TBD] and MOCK markers and writes
// docs/LAUNCH_CHECKLIST.md at the repo root, grouped by file with line
// numbers — a plain-text punch list for whoever signs off before launch.
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = fileURLToPath(new URL(".", import.meta.url));
const frontendDir = join(scriptDir, "..");
const srcDir = join(frontendDir, "src");
const repoRoot = join(frontendDir, "..");
const outputPath = join(repoRoot, "docs", "LAUNCH_CHECKLIST.md");

const MARKER_PATTERN = /\[VERIFY\]|\[TBD\]|\bMOCK\b/g;
const SCAN_EXTENSIONS = new Set([".ts", ".tsx", ".js", ".jsx"]);

function walk(dir, files = []) {
  for (const entry of readdirSync(dir)) {
    const fullPath = join(dir, entry);
    const stats = statSync(fullPath);
    if (stats.isDirectory()) {
      walk(fullPath, files);
    } else if (SCAN_EXTENSIONS.has(entry.slice(entry.lastIndexOf(".")))) {
      files.push(fullPath);
    }
  }
  return files;
}

const hits = new Map(); // relative file path -> [{ line, text }]

for (const file of walk(srcDir)) {
  const text = readFileSync(file, "utf8");
  const lines = text.split("\n");
  const fileHits = [];
  lines.forEach((line, index) => {
    if (MARKER_PATTERN.test(line)) {
      fileHits.push({ line: index + 1, text: line.trim() });
    }
    MARKER_PATTERN.lastIndex = 0;
  });
  if (fileHits.length > 0) {
    hits.set(relative(repoRoot, file).replace(/\\/g, "/"), fileHits);
  }
}

const sortedFiles = [...hits.keys()].sort();
const totalHits = sortedFiles.reduce((sum, file) => sum + hits.get(file).length, 0);

const lines = [
  "# Launch Checklist",
  "",
  `Generated by \`npm run launch:checklist\`. ${totalHits} item(s) across ${sortedFiles.length} file(s) still have a [VERIFY], [TBD] or MOCK marker — resolve or consciously accept each one before launch.`,
  "",
];

for (const file of sortedFiles) {
  lines.push(`## ${file}`, "");
  for (const hit of hits.get(file)) {
    lines.push(`- Line ${hit.line}: \`${hit.text}\``);
  }
  lines.push("");
}

writeFileSync(outputPath, lines.join("\n"), "utf8");
console.log(`Wrote ${outputPath} — ${totalHits} item(s) across ${sortedFiles.length} file(s).`);
